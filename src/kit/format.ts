// КОНТРАКТ «кита». Менять только по согласованию: от него зависят сцена (сборщик),
// библиотека предметов, витрина и дорисовка через Claude.
//
// Предмет — список простых фигур. Движок рисует их пикселями (пиксельный слой),
// поэтому простые фигуры выглядят как аккуратный пиксель-арт. Один и тот же формат
// пишем заранее руками и получаем от Claude во время фильма.
import type { PaletteName } from '../scene/palette'

export type { PaletteName }

/**
 * Единица кита в мировых единицах сцены. Страница 3.2 × 4.2 = 96 × 126 единиц кита.
 * Человечек ростом около 34 единиц — примерно четверть высоты страницы.
 */
export const KIT_UNIT = 1 / 30

/**
 * Фигуры. Размер d — габариты по осям X, Y, Z в единицах кита, если не сказано иначе.
 * - box: коробка.
 * - cyl: цилиндр по оси Y; d = [диаметр X, высота, диаметр Z].
 * - sph: шар/эллипсоид; d = диаметры.
 * - cone: конус по оси Y, вершиной вверх; d как у cyl. С k: 4 — пирамида.
 * - cap: капсула по оси Y; d = [диаметр, полная длина, диаметр Z].
 * - torus: кольцо, стоит вертикально в плоскости XY (как ручка кружки);
 *   d = [внешняя ширина, внешняя высота, толщина трубки]. Положить плашмя — r: [90, 0, 0].
 * - wedge: клин-пандус; высокая сторона слева (−X), скат вниз вправо (+X).
 * - prism: трёхгранная призма-крыша; конёк сверху вдоль Z.
 */
export type Shape = 'box' | 'cyl' | 'sph' | 'cone' | 'cap' | 'torus' | 'wedge' | 'prism'

export type Vec3 = [number, number, number]

export interface Part {
  /** Фигура. */
  s: Shape
  /** Центр фигуры. Y вверх, Y = 0 — земля (страница), предмет смотрит на +Z (в камеру). */
  p: Vec3
  /** Габариты, см. Shape. */
  d: Vec3
  /** Поворот в градусах, порядок XYZ. */
  r?: Vec3
  /** Цвет — имя из палитры (src/scene/palette.ts). */
  c: PaletteName
  /** Число граней у cyl, cone, sph: 3–24. Например, 6 — карандаш, 4 — пирамида. */
  k?: number
  /** Светится: всегда светлый тон, не темнеет в тени (лампочка, огонь, экран). */
  glow?: boolean
  /** Имя части: по нему анимация находит, например, «lid» или «wheel». */
  n?: string
}

/** Живые подсказки: код добавляет частицы и движение. at — точка в единицах кита. */
export type FxKind = 'steam' | 'smoke' | 'flame' | 'glow' | 'sparkle' | 'drip' | 'bob' | 'spin' | 'sway' | 'notes' | 'hearts'

export interface Fx {
  kind: FxKind
  at?: Vec3
  /** Для spin: имя части, которая крутится (колесо, лопасти). */
  part?: string
}

/** Как человечек обращается с предметом. */
export type Hold =
  /** в одной руке (кружка, телефон) */
  | 'hand'
  /** в обеих руках перед собой (коробка, торт) */
  | 'both'
  /** не берёт: предмет встаёт на странице (дерево, юрта, автобус) */
  | 'ground'

export interface KitModel {
  /** Латиница, snake_case, уникально в библиотеке. */
  id: string
  /** Название по-русски, именительный падеж. */
  ru: string
  kk?: string
  en?: string
  /** Основы слов для поиска по тексту: «кофе», «кофей», «кофт» нельзя — только однозначные. */
  stems: string[]
  /** Категории и признаки: food, drink, weather, nature, city, home, study, work, transport, music, animal, holiday, feeling, kz, warm, cold… */
  tags: string[]
  hold: Hold
  /**
   * Точка хвата для предметов в руке: где ладонь, в единицах кита (той же системы, что parts).
   * Сцена совмещает эту точку с ладонью человечка; нет — держит за середину.
   */
  grip?: Vec3
  /**
   * Роль в сценке по умолчанию (src/kit/scene.ts): hand — в руку, stand — декорация места 25–60,
   * detail — маленькая деталь на бумаге 6–20 (ниже обычного «ground»). Необязательно.
   */
  scene?: 'hand' | 'stand' | 'detail'
  fx?: Fx[]
  parts: Part[]
  /** Кто нарисовал: library — заранее, claude — дорисовано во время фильма. */
  by?: 'library' | 'claude'
}

