export const SONG_BY_ID: ReadonlyMap<string, ListedSong> = new Map(SONG_LIST.map((x) => [x.id, x]))

const flatName = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\p{N}]+/gu, ' ').trim()
/** Песня из списка по id ролика YouTube. */
export const findListedByYt = (yt: string | undefined) => (yt ? (SONG_LIST.find((x) => x.yt === yt) ?? null) : null)

/** Песня из списка по названию (и исполнителю, если дан): человек сам вписал «Кино — Кукушка» — у неё есть yt. */
export function findListedSong(title: string, artist?: string): ListedSong | null {
  const t = flatName(title)
  if (!t) return null
  const a = artist ? flatName(artist) : ''
  return SONG_LIST.find((x) => flatName(x.title) === t && (!a || flatName(x.artist).includes(a) || a.includes(flatName(x.artist)))) ?? null
}

