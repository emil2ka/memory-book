/** Точка на наклонённой к камере плоскости (сковорода): u — вправо, v — «вверх» по плоскости, h — над плоскостью. */
const onTilt = (c: Vec3, tiltDeg: number, u: number, v: number, h: number): Vec3 => {
  const t = (tiltDeg * Math.PI) / 180
  return [c[0] + u, c[1] + v * Math.sin(t) + h * Math.cos(t), c[2] - v * Math.cos(t) + h * Math.sin(t)]
}

